-- 1. wx_tasks 테이블 생성 (지역 및 구분 CHECK 제약조건 포함)
create table if not exists wx_tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  region text not null check (region in ('세종', '대전', '태안', '보령')),
  kind text not null check (kind in ('야외', '고소', '실내')),
  owner text not null,
  created_at timestamptz default now()
);

-- 2. RLS(행 단위 보안) 활성화 및 누구나 읽기/추가 허용 (공개용 anon 키 접근용)
alter table wx_tasks enable row level security;

create policy "누구나 일정 읽기 가능"
  on wx_tasks for select
  to anon, authenticated
  using (true);

create policy "누구나 일정 추가 가능"
  on wx_tasks for insert
  to anon, authenticated
  with check (true);

